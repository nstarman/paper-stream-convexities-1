r"""Render ``variables.yml`` and the scripts' values into ``src/tex/output/**/*.tex``.

Only the variables ``ms.tex`` cites are written: they are this rule's outputs in
the Snakefile, and everything in ``src/tex/output`` is pushed to Overleaf.

Every generated file holds complete TeX (``\qty{e12}{\Msun}``) rather than a
bare number, because ``\input`` is not expandable and so a ``\variable{}``
cannot be nested inside a siunitx argument. Every file ends with ``%`` and no
trailing newline, so ``\variable{}`` does not insert a spurious space before
whatever follows it.

Usage (a build runs it):
    uv run python src/scripts/make_variables.py

"""
# ruff: noqa: INP001, T201

import decimal
import json
import math
import re
import sys

from typing import Any, Final

from stream_convexity_paper.paths import MANUSCRIPT, VALUES
from stream_convexity_paper.variables import (
    OUTPUT_DIR,
    PARAMS,
    REPO_ROOT,
    tex_interval,
    tex_number,
    tex_qtyrange,
    tex_quantity,
)

HEADER: Final = (
    "% GENERATED by src/scripts/make_variables.py from variables.yml."
    " DO NOT EDIT.\n"
)

#: Values a figure script owns rather than variables.yml declaring: either
#: measured from a computation, or a presentation choice made in that script and
#: quoted in the manuscript. Each script writes `src/data/values/<its stem>.values.json`
#: (generated, gitignored), so this exporter runs without re-doing the computation.
DERIVED_FILES: Final = {
    "orbits": VALUES / "step_1_compute_orbits.values.json",
    "mollweide": VALUES / "step_2_plot_mollweide.values.json",
    "rates": VALUES / "step_2_plot_triaxiality.values.json",
    "nreq": VALUES / "streams_required_pcdm.values.json",
    "gd1": VALUES / "plot_gd1_convexities.values.json",
}

#: Decimal places for measured quantities quoted as a range in the manuscript.
ECC_DECIMALS: Final = 2


#: Every `\variable{...}` path the manuscript reads.
VARIABLE_RE: Final = re.compile(r"\\variable\{([^}]*)\}")
MAIN_TEX: Final = MANUSCRIPT


def cited_paths() -> set[str]:
    r"""Return the ``output/`` paths ``ms.tex`` reads via ``\variable{}``."""
    if not MAIN_TEX.is_file():
        return set()
    # Strip LaTeX comments first: the shim's own docstring shows an example
    # \variable{} call that is not a real reference.
    body = "\n".join(
        re.sub(r"(?<!\\)%.*", "", line)
        for line in MAIN_TEX.read_text(encoding="utf-8").splitlines()
    )
    return set(VARIABLE_RE.findall(body))


def tex_sigfig(x: float, digits: int = 2) -> str:
    """Round for display only, half-up, to ``digits`` significant figures.

    Trailing zeros are kept: they carry the precision claimed, so 0.90 must not
    collapse to 0.9 beside a 0.83.  Calculations always use the unrounded value;
    this is the last step before the number reaches the page.
    """
    exp = math.floor(math.log10(abs(x)))
    q = decimal.Decimal(1).scaleb(exp - digits + 1)
    d = decimal.Decimal(repr(x)).quantize(q, rounding=decimal.ROUND_HALF_UP)
    return f"{d:f}"


def _derived(key: str) -> dict[str, Any]:
    """Load one figure script's measured values."""
    path = DERIVED_FILES[key]
    if not path.is_file():
        msg = (
            f"{path.relative_to(REPO_ROOT)} is missing. It is written by the "
            "figure script that measures these values; re-run that script."
        )
        raise FileNotFoundError(msg)
    return json.loads(path.read_text(encoding="utf-8"))


def build() -> dict[str, str]:
    """Return a mapping of ``output``-relative path to rendered TeX body."""
    tri = PARAMS["triaxial_orbits"]
    pot = tri["potential"]
    host = PARAMS["host_potential"]
    orbits = _derived("orbits")
    mollweide = _derived("mollweide")
    gd1 = _derived("gd1")

    def ecc(name: str) -> str:
        return tex_interval([round(x, ECC_DECIMALS) for x in orbits[name]])

    def peak_percent(name: str) -> str:
        return tex_number(round(orbits[name] * 100))

    return {
        "triaxial/m_tot.tex": tex_quantity(host["m_tot"]),
        "triaxial/r_s.tex": tex_quantity(host["r_s"]),
        "triaxial/q1.tex": tex_quantity(pot["q1"]),
        "triaxial/q2.tex": tex_quantity(pot["q2"]),
        "triaxial/t_integrate.tex": tex_quantity(tri["t_integrate"]),
        "triaxial/orbit1_ecc.tex": ecc("orbit1_ecc"),
        "triaxial/orbit2_ecc.tex": ecc("orbit2_ecc"),
        "triaxial/orbit1_peak_convex.tex": peak_percent("orbit1_peak_convex_frac"),
        "triaxial/orbit2_peak_convex.tex": peak_percent("orbit2_peak_convex_frac"),
        "triaxial/r_near.tex": tex_quantity(
            {"value": mollweide["r_near_kpc"], "unit": "kpc"},
        ),
        "gd1/n_views.tex": tex_quantity(PARAMS["gd1"]["n_viewing_angles"]),
        "gd1/theta.tex": tex_quantity({"value": round(gd1["theta_deg"], 1), "unit": "deg"}),
        "gd1/phi.tex": tex_quantity({"value": round(gd1["phi_deg"], 1), "unit": "deg"}),
        "gd1/convex_frac.tex": tex_number(round(gd1["convex_frac"] * 100)),
        # Isotropic rates for GD-1 over the viewing directions the figure
        # samples.  Percentages, so the manuscript supplies its own \%.
        # These are NOT lambda_det: no CoM exclusion, plain contiguous runs
        # rather than bridged ones, and a non-strict threshold.  Prose that
        # sets them beside the population rates has to say so.
        "gd1/frac_any_convex.tex": tex_number(round(gd1["frac_any_convex"] * 100, 1)),
        "gd1/frac_det_ell_min.tex": tex_number(
            round(gd1["frac_det_ell_min"] * 100, 1),
        ),
        "gd1/frac_fully_convex.tex": tex_number(
            round(gd1["frac_fully_convex"] * 100, 1),
        ),
        **_cosmology_rates(),
    }


def _wald_error(nreq: dict[str, Any], index: int) -> str:
    """Percent by which the normal sample size falls short of the exact one."""
    approx = nreq["n_required_fiducial"][index]
    exact = nreq["n_required_exact"][index]
    pct = 100 * abs(exact - approx) / exact
    return f"{pct:.0f}" if pct >= 10 else f"{pct:.1f}"  # noqa: PLR2004


def _cosmology_rates() -> dict[str, str]:
    r"""Render \autoref{sec:cosmology:rates} and its two figure captions."""
    cfg = PARAMS["cosmology_rates"]
    rates = _derived("rates")
    nreq = _derived("nreq")

    def percent(value: float, decimals: int = 0) -> str:
        """Render a fraction as a percentage, keeping the decimals asked for.

        A trailing zero is significant here: a rate quoted to two decimals must
        print 8.00, not 8, beside one that prints 4.27.
        """
        if decimals:
            return f"{round(value * 100, decimals):.{decimals}f}"
        return tex_number(round(value * 100))

    def display_2sf(value: float) -> str:
        return tex_sigfig(value)

    def percent_2sf(value: float) -> str:
        """A rate as a percentage, to two significant figures."""
        return tex_sigfig(value * 100)

    def eta_region_mean() -> float:
        """Suppression ratio if the rates are read at the region-mean flattenings.

        The single-qbar approximation picks one representative flattening per
        model. Averaging qbar over each polygon instead is the natural
        alternative, and the ratio of the two answers is the sensitivity quoted
        in sec:cosmology:rates.
        """
        return (
            rates["lambda_arc_sidm_region_mean"] / rates["lambda_arc_cdm_region_mean"]
        )

    def n_required_ratio() -> float:
        r"""How much larger the catalogue would have to be at that eta.

        N scales as 1 / (1 - sqrt(eta))^2 at fixed lambda_C
        (eq:cosmology:N_required), so only the eta factor survives the ratio.
        """
        return (1.0 - math.sqrt(nreq["eta_fid"])) ** 2 / (
            1.0 - math.sqrt(eta_region_mean())
        ) ** 2

    def round_sig(value: float, sig: int = 2) -> float:
        """Round to `sig` significant figures, as a float (for counts)."""
        if value == 0:
            return 0.0
        return round(value, -int(math.floor(math.log10(abs(value)))) + (sig - 1))

    def count(value: float, sig: int = 2) -> str:
        r"""Render a stream count, wrapped in \num{} for digit grouping."""
        return rf"\num{{{round_sig(value, sig):.0f}}}"

    def count_plain(value: float, sig: int = 2) -> str:
        """Render a rounded count as bare digits, for siunitx range macros."""
        return f"{round_sig(value, sig):.0f}"

    def sci(value: float, sig: int = 2) -> str:
        """Render a p-value in siunitx scientific notation."""
        return rf"\num{{{value:.{sig - 1}e}}}"

    def times_ten(value: float) -> str:
        r"""Render a count as $a\times10^{b}$ rather than as digits."""
        exponent = math.floor(math.log10(abs(value)))
        mantissa = value / 10**exponent
        mant = (
            str(round(mantissa))
            if abs(mantissa - round(mantissa)) < 1e-9  # noqa: PLR2004
            else f"{mantissa:g}"
        )
        return rf"{mant}\times10^{{{exponent}}}"

    worked = nreq["worked_example"]

    return {
        # Monte-Carlo configuration (variables.yml; consumed by step_1).
        # Counts keep \num{} so siunitx groups the digits if they ever grow.
        "cosmology/n_orbits.tex": rf"\num{{{tex_number(cfg['n_orbits']['value'])}}}",
        "cosmology/n_views.tex": (
            rf"\num{{{tex_number(cfg['n_phi']['value'] * cfg['n_theta']['value'])}}}"
        ),
        # The range orbits are SAMPLED from, not the range they achieve.
        "cosmology/e_range.tex": tex_interval(cfg["e_range"]),
        "cosmology/r_range.tex": tex_qtyrange(cfg["r_range"]),
        "cosmology/i_range.tex": tex_qtyrange(cfg["i_range"]),
        "cosmology/t_integrate.tex": tex_quantity(cfg["t_integrate"]),
        "cosmology/window.tex": tex_quantity(
            {"value": 2 * cfg["window_half"]["value"], "unit": "Gyr"},
        ),
        "cosmology/r_exclude.tex": tex_quantity(cfg["r_exclude"]),
        # Plot-time choices and measured readings (step_2_plot_triaxiality).
        "cosmology/ell_min.tex": tex_quantity(
            {"value": rates["ell_min_kpc"], "unit": "kpc"},
        ),
        "cosmology/band_pctl.tex": (
            rf"{rates['band_pctl'][0]}\text{{--}}{rates['band_pctl'][1]}"
        ),
        "cosmology/percentile_levels.tex": "/".join(
            tex_number(v) for v in rates["percentile_levels"]
        ),
        # Declared inputs (variables.yml), not measured: selected points.
        # Printed to two significant figures: the shape literature does not
        # support quoting a flattening to 1e-3. The full value is what the
        # figure and the rates are computed from; only the display rounds.
        "cosmology/qbar_cdm.tex": display_2sf(rates["qbar_cdm"]),
        "cosmology/qbar_sidm.tex": display_2sf(rates["qbar_sidm"]),
        "cosmology/lambda_arc_cdm.tex": percent_2sf(rates["lambda_arc_cdm"]),
        "cosmology/lambda_arc_sidm.tex": percent_2sf(rates["lambda_arc_sidm"]),
        # How much the SIDM rate moves for a shift in the representative
        # flattening too small to show at the printed precision.
        "cosmology/qbar_shift.tex": f"{rates['qbar_sidm_display_shift']:.4f}",
        "cosmology/lambda_sidm_shift.tex": percent(
            abs(rates["lambda_arc_sidm_shift_frac"]),
        ),
        "cosmology/lambda_det_cdm.tex": percent_2sf(rates["lambda_det_cdm"]),
        # Halo-shape region bounds, quoted in sec:cosmology:rates.
        **{
            f"cosmology/{_k}_range.tex": (
                rf"\numrange{{{_v[0]:.2f}}}{{{_v[1]:.2f}}}"
            )
            for _k, _v in rates["region_bounds"].items()
        },
        # q̄ turnover in b/a, quoted in sec:cosmology:rates.  q̄ to three
        # decimals: the whole effect is under 0.01.
        "cosmology/qbar_turnover_ba_range.tex": (
            rf"\numrange{{{rates['qbar_turnover']['ba_lo']:.2f}}}"
            rf"{{{rates['qbar_turnover']['ba_hi']:.2f}}}"
        ),
        # How little of the CDM/SIDM q̄ separation the b/a axis can account for.
        # Quoted as "at most", so round the bound UP to the last digit shown.
        "cosmology/qbar_ba_spread.tex": (
            f"{math.ceil(rates['qbar_ba_spread'] * 1000) / 1000:.3f}"
        ),
        "cosmology/qbar_region_separation.tex": (
            f"{rates['qbar_region_separation']:.3f}"
        ),
        "cosmology/qbar_turnover_ca.tex": f"{rates['qbar_turnover']['ca']:.2f}",
        "cosmology/qbar_turnover_ba.tex": f"{rates['qbar_turnover']['ba']:.2f}",
        "cosmology/qbar_turnover_qbar_peak.tex": (
            f"{rates['qbar_turnover']['qbar_peak']:.3f}"
        ),
        "cosmology/qbar_turnover_qbar_oblate.tex": (
            f"{rates['qbar_turnover']['qbar_oblate']:.3f}"
        ),
        "cosmology/qbar_turnover_rate_peak.tex": percent(
            rates["qbar_turnover"]["rate_peak"], 1,
        ),
        "cosmology/qbar_turnover_rate_oblate.tex": percent(
            rates["qbar_turnover"]["rate_oblate"], 1,
        ),
        "cosmology/lambda_det_sidm.tex": percent_2sf(rates["lambda_det_sidm"]),
        # Forecast parameters (streams_required_pcdm).
        # Two decimals, matching how the caption writes the eta band.
        "cosmology/eta_lo.tex": f"{nreq['eta_lo']:.2f}",
        "cosmology/eta_fid.tex": f"{nreq['eta_fid']:.2f}",
        "cosmology/eta_hi.tex": f"{nreq['eta_hi']:.2f}",
        # A bound, not a measurement, so one decimal.
        "cosmology/eta_sidm_regime.tex": f"{nreq['eta_sidm_regime']:.1f}",
        # Sensitivity of the forecast to the single-qbar approximation.
        # The SIDM relaxation map of eq:cosmology:sidm_relaxation.
        "cosmology/sidm_ca_offset.tex": f"{100 * rates['sidm_ca_offset']:.1f}",
        "cosmology/sidm_relaxation.tex": f"{rates['sidm_relaxation']:.3f}",
        "cosmology/auriga_ca_median.tex": f"{rates['auriga_ca_median']:.2f}",
        "cosmology/eta_region_mean.tex": f"{eta_region_mean():.2f}",
        # Two decimals: the region integral moves N by under a per cent, which
        # one decimal rounds to a bare 1.0 and so reports as no change at all.
        "cosmology/n_required_ratio.tex": f"{n_required_ratio():.2f}",
        # Euclid projection; the dashed curve in fig:cosmology:zlr and the
        # survey line in fig:cosmology:Nreq are both drawn at this N.
        "cosmology/n_euclid_min.tex": count(nreq["n_euclid_min"]),
        "cosmology/catalog_sizes.tex": ",".join(
            f"10^{{{round(math.log10(n))}}}" for n in nreq["catalogue_sizes"]
        ),
        # Required catalogue size at N_sigma = 1, 2, 3, 5. Two significant
        # figures: these are order-of-magnitude forecasts.
        "cosmology/n_required_fiducial.tex": ", ".join(
            count(n) for n in nreq["n_required_fiducial"]
        ),
        "cosmology/n_required_optimistic.tex": ", ".join(
            count(n) for n in nreq["n_required_optimistic"]
        ),
        "cosmology/eta_det.tex": f"{nreq['eta_det']:.2f}",
        # How far the normal sample-size formula sits from the exact binomial
        # requirement. Sawtooth in N, so the 1-sigma entry is the unstable one.
        "cosmology/wald_error_1sigma.tex": _wald_error(nreq, 0),
        "cosmology/wald_error_3sigma.tex": _wald_error(nreq, 2),
        # 2-sigma to 5-sigma span, rendered whole: \numrange cannot take a
        # \variable{}, since \input is not expandable inside a siunitx argument.
        # 2-sigma to 5-sigma span at the arc-length (challenging) rates.
        "cosmology/n_required_fiducial_range.tex": (
            rf"\numrange{{{count_plain(nreq['n_required_fiducial'][1])}}}"
            rf"{{{count_plain(nreq['n_required_fiducial'][3])}}}"
        ),
        "cosmology/n_sigma_local_group.tex": f"{nreq['n_sigma_local_group']:.2f}",
        "cosmology/n_required_optimistic_range.tex": (
            rf"\numrange{{{count_plain(nreq['n_required_optimistic'][1])}}}"
            rf"{{{count_plain(nreq['n_required_optimistic'][3])}}}"
        ),
        "cosmology/n_required_optimistic_3sigma.tex": count(
            nreq["n_required_optimistic"][2],
        ),
        "cosmology/lambda_det_over_fiducial.tex": (
            f"{round_sig(nreq['lambda_det_over_fiducial']):g}"
        ),
        "cosmology/n_required_3sigma_eta_lo.tex": count(
            nreq["n_required_3sigma_eta_lo"],
        ),
        "cosmology/n_required_3sigma_eta_hi.tex": count(
            nreq["n_required_3sigma_eta_hi"],
        ),
        # Worked catalogue, at the fiducial model pair.
        "cosmology/worked_n.tex": times_ten(worked["n_streams"]),
        "cosmology/worked_k_cdm.tex": str(int(worked["k_if_cdm"])),
        "cosmology/worked_k_sidm.tex": str(int(worked["k_if_sidm"])),
        "cosmology/worked_p_sidm.tex": sci(worked["p_reject_sidm"]),
        "cosmology/worked_p_cdm.tex": sci(worked["p_reject_cdm"]),
        "cosmology/worked_z_sidm.tex": f"{worked['z_reject_sidm']:.1f}",
        "cosmology/worked_z_cdm.tex": f"{worked['z_reject_cdm']:.1f}",
        "cosmology/worked_z_sidm_wald.tex": f"{worked['z_reject_sidm_wald']:.1f}",
        "cosmology/worked_z_cdm_wald.tex": f"{worked['z_reject_cdm_wald']:.1f}",
        "cosmology/worked_n_sigma.tex": f"{worked['n_sigma_balanced']:.1f}",
    }


def render(body: str) -> str:
    """Wrap a rendered value in its header and newline-swallowing terminator."""
    return f"{HEADER}{body}%"


def write() -> int:
    """Write every variable ``ms.tex`` cites. Return a shell exit code."""
    rendered = build()
    cited = cited_paths()
    # A \variable{} pointing at a path we do not generate breaks the LaTeX build.
    dangling = sorted(cited - {f"output/{relpath}" for relpath in rendered})
    if dangling:
        print("ms.tex reads variables that make_variables.py never generates:")
        print("\n".join(f"  {path}" for path in dangling))
        return 1
    for relpath, body in rendered.items():
        if f"output/{relpath}" not in cited:
            continue
        path = OUTPUT_DIR / relpath
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(body), encoding="utf-8")
        print(f"wrote {path.relative_to(OUTPUT_DIR.parent)}  ->  {body}")
    return 0


if __name__ == "__main__":
    sys.exit(write())
